import React, { useState, useEffect, useRef } from 'react';
import { Scale, RefreshCw } from 'lucide-react';
import {
  AdvisoryRecommendation,
  AdvisorySummary
} from '../types/twin';
import {
  fetchRecommendations,
  fetchAdvisorySummary,
  triggerRuleEvaluation
} from '../services/api';
import { useFocusTrap } from '../hooks/useFocusTrap';
import { AdvisoryCard } from './advisory/AdvisoryCard';

interface AdvisoryCenterModalProps {
  isOpen: boolean;
  onClose: () => void;
  onSelectEntity?: (entityId: string) => void;
  onOpenScenarioStudio?: () => void;
}

export const AdvisoryCenterModal: React.FC<AdvisoryCenterModalProps> = ({
  isOpen,
  onClose,
  onSelectEntity,
  onOpenScenarioStudio
}) => {
  const modalRef = useRef<HTMLDivElement>(null);
  const [recommendations, setRecommendations] = useState<AdvisoryRecommendation[]>([]);
  const [summary, setSummary] = useState<AdvisorySummary | null>(null);

  // Focus trapping and Escape key closing per WCAG 2.1 AA
  useFocusTrap(modalRef, isOpen, onClose);
  const [domainFilter, setDomainFilter] = useState<string>('ALL');
  const [statusFilter, setStatusFilter] = useState<string>('ALL');
  const [loading, setLoading] = useState<boolean>(false);
  const [evaluating, setEvaluating] = useState<boolean>(false);

  const loadData = async () => {
    try {
      setLoading(true);
      const [recs, sum] = await Promise.all([
        fetchRecommendations(
          domainFilter === 'ALL' ? undefined : domainFilter,
          statusFilter === 'ALL' ? undefined : statusFilter
        ),
        fetchAdvisorySummary()
      ]);
      setRecommendations(recs);
      setSummary(sum);
    } catch (err) {
      console.error('Failed to load advisory recommendations', err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    if (isOpen) {
      loadData();
    }
  }, [isOpen, domainFilter, statusFilter]);

  if (!isOpen) return null;

  const handleTriggerEvaluate = async () => {
    try {
      setEvaluating(true);
      await triggerRuleEvaluation();
      await loadData();
    } catch (err) {
      console.error('Failed to evaluate rules', err);
    } finally {
      setEvaluating(false);
    }
  };

  return (
    <div className="modal-backdrop" onClick={onClose}>
      <div
        ref={modalRef}
        tabIndex={-1}
        role="dialog"
        aria-modal="true"
        aria-labelledby="advisory-title"
        className="advisory-modal-content"
        onClick={(e) => e.stopPropagation()}
      >
        {/* Modal Header */}
        <div className="modal-header">
          <div className="modal-header-left">
            <h2 id="advisory-title" className="modal-title">
              Advisory Decision Support Center
            </h2>
            <span className="provenance-tag prov-predicted">EVIDENCE-BACKED ADVISORIES</span>
          </div>
          <button className="btn-close" onClick={onClose} aria-label="Close Advisory Center">
            &times;
          </button>
        </div>

        {/* Governance Mandate Banner */}
        <div className="governance-alert-banner">
          <div className="governance-icon"><Scale size={18} aria-hidden="true" color="#F59E0B" /></div>
          <div className="governance-text">
            <strong>Mandatory Governance Policy:</strong> All recommendations generated by the twin rule engine
            are strictly advisory decision support. No automated actuation is permitted. Every operational action
            requires verified human authorization by municipal officials or facility managers.
          </div>
        </div>

        {/* Metrics Summary Strip */}
        {summary && (
          <div className="advisory-metrics-strip">
            <div className="advisory-metric-card">
              <span className="metric-label">Active Advisories</span>
              <span className="metric-val">{summary.totalActive}</span>
            </div>
            <div className="advisory-metric-card">
              <span className="metric-label">Critical Priority</span>
              <span className="metric-val text-critical">{summary.criticalCount}</span>
            </div>
            <div className="advisory-metric-card">
              <span className="metric-label">Warning Priority</span>
              <span className="metric-val text-warning">{summary.warningCount}</span>
            </div>
            <div className="advisory-metric-card">
              <span className="metric-label">Traffic Domain</span>
              <span className="metric-val">{summary.byDomain['TRAFFIC'] || 0}</span>
            </div>
            <div className="advisory-metric-card">
              <span className="metric-label">Energy Domain</span>
              <span className="metric-val">{summary.byDomain['ENERGY'] || 0}</span>
            </div>
            <button
              className="btn btn-secondary btn-evaluate"
              onClick={handleTriggerEvaluate}
              disabled={evaluating}
              title="Evaluate active twin state and forecasts against deterministic rules"
              style={{ display: 'inline-flex', alignItems: 'center', gap: '6px' }}
            >
              <RefreshCw size={13} className={evaluating ? 'animate-spin' : ''} />
              <span>{evaluating ? 'Evaluating...' : 'Refresh Rules'}</span>
            </button>
          </div>
        )}

        {/* Filter Controls */}
        <div className="advisory-filters-row">
          <div className="filter-group">
            <label className="filter-label">Domain:</label>
            <div className="filter-chips">
              {['ALL', 'TRAFFIC', 'ENERGY', 'ENVIRONMENT'].map((dom) => (
                <button
                  key={dom}
                  className={`chip-btn ${domainFilter === dom ? 'active' : ''}`}
                  onClick={() => setDomainFilter(dom)}
                >
                  {dom}
                </button>
              ))}
            </div>
          </div>

          <div className="filter-group">
            <label className="filter-label">Status:</label>
            <div className="filter-chips">
              {['ALL', 'ACTIVE', 'UNDER_REVIEW', 'ACKNOWLEDGED', 'DISMISSED'].map((st) => (
                <button
                  key={st}
                  className={`chip-btn ${statusFilter === st ? 'active' : ''}`}
                  onClick={() => setStatusFilter(st)}
                >
                  {st.replace('_', ' ')}
                </button>
              ))}
            </div>
          </div>
        </div>

        {/* Recommendations List Body */}
        <div className="advisory-list-body">
          {loading ? (
            <div className="loading-state">Loading advisory records...</div>
          ) : recommendations.length === 0 ? (
            <div className="empty-state">
              <p>No recommendations match the selected filters.</p>
            </div>
          ) : (
            recommendations.map((rec) => (
              <AdvisoryCard
                key={rec.recommendationId}
                advisory={rec}
                initialReviewerName="Municipal Traffic Cell Officer"
                onNavigateToEntity={(entityId) => {
                  if (onSelectEntity) {
                    onSelectEntity(entityId);
                    onClose();
                  }
                }}
                onNavigateToScenarios={() => {
                  if (onOpenScenarioStudio) {
                    onOpenScenarioStudio();
                    onClose();
                  }
                }}
                onAdvisoryUpdated={loadData}
              />
            ))
          )}
        </div>
      </div>
    </div>
  );
};
